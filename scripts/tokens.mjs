#!/usr/bin/env node
/**
 * Generates src/styles/tokens.css from src/styles/tokens3d.ts, so the CSS and
 * the WebGL scene can't drift apart.
 *
 *   npm run tokens          write the file
 *   npm run tokens:check    exit 1 if the file is stale (part of `npm run lint`)
 *
 * Runs tokens3d.ts directly with Node's built-in type stripping (Node ≥ 22.18).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as t from "../src/styles/tokens3d.ts";

const OUT = fileURLToPath(new URL("../src/styles/tokens.css", import.meta.url));
const rem = (px) => `${px / 16}rem`;
const bez = (p) => `cubic-bezier(${p.join(", ")})`;
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const block = (selector, vars, indent = "") =>
  `${indent}${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `${indent}  ${k}: ${v};`)
    .join("\n")}\n${indent}}`;

const { color, layout } = t;

// Plain custom properties: read by hand-written CSS and by @theme inline below.
const root = {
  // A. colour
  ...Object.fromEntries(Object.entries(color).map(([k, v]) => [`--c-${kebab(k)}`, v])),
  // B. spacing (named steps; Tailwind's own 4px multiplier covers p-4, gap-6 …)
  ...Object.fromEntries(Object.entries(t.space).map(([k, v]) => [`--space-${k}`, rem(v)])),
  // E. spatial
  "--gutter": `clamp(${rem(layout.gutter.min)}, ${layout.gutter.vw}vw, ${rem(layout.gutter.max)})`,
  "--section-py": `clamp(${rem(layout.sectionPadding.min)}, ${layout.sectionPadding.vh}vh, ${rem(layout.sectionPadding.max)})`,
  "--nav-h": rem(layout.navHeight),
  "--stage-h": layout.stageBand,
  "--content-max": t.measure.content,
  "--body-max": t.measure.body,
  "--hang": "0px",
  "--column-w": `${layout.column.lg * 100}%`,
  "--article-max": t.measure.article,
  // D. motion durations (Tailwind has no duration namespace: use duration-(--dur-base))
  ...Object.fromEntries(Object.entries(t.duration).map(([k, v]) => [`--dur-${k}`, `${v}ms`])),
  "color-scheme": "dark",
};

// Utilities that point at the variables above (bg-bg, text-text-muted, font-editorial, p-section …).
const themeInline = {
  ...Object.fromEntries(Object.keys(color).map((k) => [`--color-${kebab(k)}`, `var(--c-${kebab(k)})`])),
  ...Object.fromEntries(Object.entries(t.fontFamily).map(([k, v]) => [`--font-${k}`, v])),
  "--spacing-section": "var(--section-py)",
  "--spacing-gutter": "var(--gutter)",
};

// Literal theme values, always emitted so hand-written CSS can use var(--text-body) etc.
const themeStatic = {
  ...Object.fromEntries(
    Object.entries(t.typeScale).flatMap(([k, s]) => [
      [`--text-${k}`, t.fluid(s.min, s.max)],
      [`--text-${k}--line-height`, String(s.lineHeight)],
      ...(s.tracking ? [[`--text-${k}--letter-spacing`, s.tracking]] : []),
      ...(s.weight ? [[`--text-${k}--font-weight`, String(s.weight)]] : []),
    ]),
  ),
  "--spacing": rem(t.BASE_UNIT),
  ...Object.fromEntries(Object.entries(t.radius).map(([k, v]) => [`--radius-${k}`, `${v}px`])),
  ...Object.fromEntries(Object.entries(t.breakpoint).map(([k, v]) => [`--breakpoint-${k}`, rem(v)])),
  ...Object.fromEntries(Object.entries(t.easing).map(([k, v]) => [`--ease-${kebab(k)}`, bez(v)])),
};

const css = `/* GENERATED by scripts/tokens.mjs from src/styles/tokens3d.ts — do not edit.
   Change the TypeScript tokens, then run \`npm run tokens\`. */

${block(":root", root)}

@media (min-width: ${rem(t.breakpoint.md)}) {
  :root {
    --hang: ${rem(layout.hang)};
  }
}

/* The mobile 3D band collapses on desktop, where the stage is a fixed side panel. */
@media (min-width: ${rem(t.breakpoint.lg)}) {
  :root {
    --stage-h: 0px;
  }
}

@media (min-width: ${rem(t.breakpoint.xl)}) {
  :root {
    --column-w: ${layout.column.xl * 100}%;
  }
}

${block("@theme inline", themeInline)}

${block("@theme static", themeStatic)}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== css) {
    console.error("src/styles/tokens.css is out of date with tokens3d.ts. Run: npm run tokens");
    process.exit(1);
  }
  console.log("tokens.css is up to date.");
} else {
  writeFileSync(OUT, css);
  console.log("Wrote src/styles/tokens.css");
}
